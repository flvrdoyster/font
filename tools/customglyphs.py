def _assemble(body):
    """11-row body (rows 2..12) -> full 16-row grid of 8-col strings."""
    grid = ["........"] * 16
    for i, row in enumerate(body):
        grid[2 + i] = row
    return grid


def _to_rows(grid, width=8):
    """Grid of '#/.' strings -> list of row bitmasks (pixelfont format)."""
    rows = []
    for line in grid:
        val = 0
        for x in range(width):
            if x < len(line) and line[x] == "#":
                val |= (1 << (width - 1 - x))
        rows.append(val)
    return rows


def _build():
    out = {}
    for ch, body in {**_CAP, **_DIGIT}.items():
        out[ord(ch)] = (8, _to_rows(_assemble(body)))
    return out


# codepoint -> (width_px, [row bitmasks])
GLYPHS = _build()
