def _to_rows(grid):
    width = len(grid[0])
    rows = []
    for line in grid:
        val = 0
        for x in range(width):
            if x < len(line) and line[x] == "#":
                val |= (1 << (width - 1 - x))
        rows.append(val)
    return width, rows


def _build():
    out = {}
    for ch, grid in GLYPHS_SRC.items():
        width, rows = _to_rows(grid)
        out[ord(ch)] = (width, rows)
    return out


# codepoint -> (width_px, [row bitmasks])
GLYPHS = _build()
